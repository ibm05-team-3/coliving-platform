-- users 테이블. email은 연락처이며 비어 있을 수 있다. 로그인 이메일은 user_email_accounts.email 이다.
DROP TABLE IF EXISTS user_roles CASCADE;
DROP TABLE IF EXISTS user_social_accounts CASCADE;
DROP TABLE IF EXISTS user_email_accounts CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- email, name, phone, address 는 Envelope Encryption 암호문(TEXT)이다.
    -- 형식: env1. + Base64(version, kekVersion, wrapIv, wrappedDek, dataIv, ciphertext)
    -- KEK(app.crypto.key)로 DEK를 감싸고, DEK로 값을 AES-256-GCM 암호화한다.
    -- 접두사 없는 기존 평문은 다음 저장 전까지 그대로 읽는다. nickname 은 평문이다.
    email                TEXT,
    name                 TEXT,
    nickname             VARCHAR(100),
    phone                TEXT,
    address              TEXT,
    contract_language    VARCHAR(10),
    enabled              BOOLEAN NOT NULL DEFAULT TRUE,
    account_non_locked   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP
);

COMMENT ON COLUMN users.email IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM. 접두사 없는 값은 기존 평문.';
COMMENT ON COLUMN users.name IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM. 접두사 없는 값은 기존 평문.';
COMMENT ON COLUMN users.phone IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM. 접두사 없는 값은 기존 평문.';
COMMENT ON COLUMN users.address IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM. 접두사 없는 값은 기존 평문.';

-- 계정 역할. 비회원(GUEST)은 로그인하지 않은 방문자라 이 테이블에 넣지 않는다.
-- USER 회원, CANDIDATE 후보자, RESIDENT 입주자, ADMIN 관리자
CREATE TABLE user_roles (
    user_id   BIGINT NOT NULL,
    role      VARCHAR(255) NOT NULL,
    CONSTRAINT user_roles_pkey PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT user_roles_role_check CHECK (role IN ('USER', 'CANDIDATE', 'RESIDENT', 'ADMIN'))
);

-- user_email_accounts 테이블 (이메일 로그인, 사용자당 1행)
CREATE TABLE user_email_accounts (
    user_id      BIGINT PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT uk_user_email_accounts_email UNIQUE (email),
    CONSTRAINT fk_user_email_accounts_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

-- user_social_accounts 테이블
CREATE TABLE user_social_accounts (
    id              VARCHAR(255) PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    provider_type   VARCHAR(255) NOT NULL,
    provider_id     VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT fk_user_social_accounts_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

-- 확인용
SELECT * FROM users;
SELECT * FROM user_roles;
SELECT * FROM user_email_accounts;
SELECT * FROM user_social_accounts;
