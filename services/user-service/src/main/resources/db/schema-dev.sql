-- user-service DB 초기화 스크립트
DROP DATABASE IF EXISTS user_service;
CREATE DATABASE user_service ENCODING 'UTF8';

\c user_service;

-- users 테이블
DROP TABLE IF EXISTS user_roles CASCADE;
DROP TABLE IF EXISTS user_social_accounts CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                VARCHAR(255) NOT NULL,
    password             VARCHAR(255),
    name                 VARCHAR(100) NOT NULL,
    phone                VARCHAR(255),
    address              VARCHAR(511),
    contract_language    VARCHAR(10),
    enabled              BOOLEAN NOT NULL DEFAULT TRUE,
    account_non_locked   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- user_roles 테이블 (ElementCollection)
CREATE TABLE user_roles (
    user_id   BIGINT NOT NULL,
    role      VARCHAR(255) NOT NULL,
    CONSTRAINT user_roles_pkey PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- user_social_accounts 테이블
CREATE TABLE user_social_accounts (
    id              VARCHAR(255) PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    provider_type   VARCHAR(255) NOT NULL,
    provider_id     VARCHAR(255) NOT NULL,
    email           VARCHAR(255),
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT fk_user_social_accounts_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

-- 확인용
SELECT * FROM users;
SELECT * FROM user_roles;
SELECT * FROM user_social_accounts;
